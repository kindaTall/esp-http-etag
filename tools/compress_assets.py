#!/usr/bin/env python3
"""
ESP HTTP ETag Asset Compression Tool

Compresses web assets (HTML, CSS, JS, SVG) using gzip and generates ETags for
efficient HTTP caching. Creates etags.h header file for use with esp_http_etag.

Usage:
    python compress_assets.py [config_file]

Configuration:
    By default, looks for compress_config.json next to this script.
    If not found, you can specify a custom config file path as argument.

    Example compress_config.json:
    {
      "targets": [
        {
          "directory": "dashboard/www",
          "files": ["dashboard.html", "*.css", "*.js"]
        },
        {
          "directory": "network/www",
          "files": ["*.html"]
        }
      ]
    }

Output:
    - Creates .gz files next to each source file
    - Generates etags.h in each directory with ETag definitions
"""
import os
import sys
import gzip
import json
import hashlib
import configparser
from pathlib import Path
from typing import List, Dict, Tuple, Union

# ============================================================================
# COMPRESSION FUNCTIONS
# ============================================================================

def gzip_file(file_path: Path, compresslevel: int = 9) -> str:
    """
    Gzip compress a file and save as .gz

    Args:
        file_path: Path to source file
        compresslevel: Compression level 1-9 (9 = maximum compression)

    Returns:
        ETag (SHA256 hash) of compressed content
    """
    with open(file_path, "rb") as f_in:
        content = f_in.read()

    compressed = gzip.compress(content, compresslevel=compresslevel)

    gz_path = Path(str(file_path) + ".gz")
    with open(gz_path, "wb") as f_out:
        f_out.write(compressed)

    etag = generate_etag(compressed)

    orig_size = len(content)
    comp_size = len(compressed)
    ratio = (1 - comp_size / orig_size) * 100 if orig_size > 0 else 0

    print(f"  {file_path.name}: {orig_size} -> {comp_size} bytes ({ratio:.1f}% reduction)")

    return etag


def generate_etag(content: bytes) -> str:
    """
    Generate SHA256-based ETag for content

    Args:
        content: Compressed file content

    Returns:
        64-character hex SHA256 hash
    """
    return hashlib.sha256(content).hexdigest()


def process_files(base: Path, file_patterns: List[str], compresslevel: int = 9) -> Dict[str, Dict[str, str]]:
    """
    Process and compress files matching patterns

    Args:
        base: Base directory path
        file_patterns: List of filenames or glob patterns
        compresslevel: Compression level 1-9

    Returns:
        Dictionary mapping filename to {etag, var_name}
    """
    results = {}

    for pattern in file_patterns:
        file_paths = list(base.glob(pattern))
        if not file_paths:
            print(f"  WARNING: File not found: {base / pattern}")
            continue

        for file_path in file_paths:
            if not file_path.is_file():
                continue

            filename = file_path.name

            # Skip already processed files and .gz files
            if filename in results or filename.endswith(".gz"):
                continue

            etag = gzip_file(file_path, compresslevel)

            # Convert filename to valid C variable name
            # Example: "dashboard.html" -> "dashboard_html_gz"
            var_name = filename.replace(".", "_").replace("-", "_") + "_gz"

            results[filename] = {"etag": etag, "var_name": var_name}

    return results


def write_header_file(output_path: Path, results: Dict[str, Dict[str, str]]):
    """
    Write C header file with ETag definitions

    Args:
        output_path: Path to output etags.h
        results: Processed files with their ETags
    """
    with open(output_path, "w") as f:
        f.write("/**\n")
        f.write(" * @file etags.h\n")
        f.write(" * @brief Auto-generated ETags for compressed web assets\n")
        f.write(" *\n")
        f.write(" * Generated by compress_assets.py from esp_http_etag module\n")
        f.write(" * DO NOT EDIT MANUALLY - Run compress_assets.py to regenerate\n")
        f.write(" */\n")
        f.write("#pragma once\n\n")

        # Sort by filename for consistent output
        for filename in sorted(results.keys()):
            data = results[filename]
            etag = data["etag"]
            var_name = data["var_name"]
            f.write(f'#define {var_name}_etag "{etag}"\n')

    print(f"  Generated: {output_path}")


# ============================================================================
# CONFIGURATION LOADING
# ============================================================================

def load_config(config_path: Path) -> Tuple[Union[Path, None], List[Tuple[str, List[str]]]]:
    """
    Load compression configuration from JSON file

    Args:
        config_path: Path to compress_config.json

    Returns:
        Tuple of (root_path, targets)
        - root_path: Optional root directory from config (None if not specified)
        - targets: List of (directory, file_patterns) tuples
    """
    try:
        with open(config_path, 'r') as f:
            config_data = json.load(f)

        # Get optional root directory
        root = config_data.get("root")
        root_path = None
        if root:
            root_path = (config_path.parent / root).resolve()
            if not root_path.exists():
                print(f"WARNING: Configured root directory does not exist: {root_path}")
                root_path = None

        targets = config_data.get("targets", [])
        result = []

        for target in targets:
            directory = target.get("directory")
            files = target.get("files", [])

            if directory and files:
                result.append([directory, files])
            else:
                print(f"WARNING: Invalid target entry (missing directory or files): {target}")

        return root_path, result

    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in config file: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Failed to load config file: {e}")
        sys.exit(1)


def resolve_target_directory(rel_dir: str, config_root: Union[Path, None]) -> Union[Path, None]:
    """
    Resolve target directory path using flexible resolution strategy

    Args:
        rel_dir: Directory path from config (may be absolute or relative)
        config_root: Optional root directory from config

    Returns:
        Resolved absolute Path or None if not found

    Resolution strategy:
        1. If path is absolute, use it directly
        2. If config has root, resolve relative to root
        3. Otherwise, search up parent directories from cwd
    """
    dir_path = Path(rel_dir)

    # 1. Try absolute path
    if dir_path.is_absolute():
        return dir_path if dir_path.exists() else None

    # 2. If config has root, resolve relative to root
    if config_root:
        resolved = (config_root / dir_path).resolve()
        return resolved if resolved.exists() else None

    # 3. Search up parent directories from cwd
    current = Path.cwd().resolve()
    while True:
        candidate = (current / dir_path).resolve()
        if candidate.exists():
            return candidate

        # Move up one level
        parent = current.parent
        if parent == current:
            # Reached filesystem root
            break
        current = parent

    return None


def find_config_file() -> Union[Path, None]:
    """
    Find configuration file in standard locations

    Returns:
        Path to config file or None if not found
    """
    # 1. Check if passed as command line argument
    if len(sys.argv) > 1:
        config_path = Path(sys.argv[1])
        if config_path.exists():
            return config_path
        else:
            print(f"ERROR: Config file not found: {config_path}")
            sys.exit(1)

    # 2. Look in script's tools directory (self-contained)
    script_dir = Path(__file__).parent
    config_path = script_dir / "compress_config.json"
    if config_path.exists():
        return config_path

    # 3. Try current directory
    config_path = Path.cwd() / "compress_config.json"
    if config_path.exists():
        return config_path

    # 4. Check if template exists and suggest copying it
    template_path = script_dir / "compress_config.json.template"

    if template_path.exists():
        print("=" * 70)
        print("ERROR: compress_config.json not found")
        print("=" * 70)
        print(f"\nTemplate available at: {template_path}")
        print(f"\nTo set up (self-contained):")
        print(f"  cp {template_path} {script_dir / 'compress_config.json'}")
        print(f"  # Edit {script_dir / 'compress_config.json'}")
        print(f"\nOr in current directory:")
        print(f"  cp {template_path} compress_config.json")
        print("  # Edit compress_config.json")
        print("\n" + "=" * 70)

    return None


