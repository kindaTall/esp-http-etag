# PROJECT ROOT DISCOVERY
# ============================================================================

def is_git_root(directory: Path) -> bool:
    """Check if directory is a git repository root"""
    git_dir = directory / ".git"
    return git_dir.exists() and (git_dir.is_dir() or git_dir.is_file())


def find_project_root(start_path: Union[str, Path]) -> Union[Path, None]:
    """
    Find project root by traversing up to git root

    Args:
        start_path: Starting directory

    Returns:
        Path to project root or None if not found
    """
    current = Path(start_path).resolve()

    # Traverse up until we find a git root
    while current.parent != current:
        if is_git_root(current):
            return current
        current = current.parent

    return None


def find_component_library_root(start_path: Union[str, Path]) -> Union[Path, None]:
    """
    Find component_library directory within project

    Args:
        start_path: Starting directory

    Returns:
        Path to component_library or None if not found
    """
    # First find git root
    project_root = find_project_root(start_path)
    if project_root is None:
        return None

    # Check if component_library exists
    component_lib = project_root / "component_library"
    if component_lib.exists() and component_lib.is_dir():
        return component_lib

    return project_root


# ============================================================================
# MAIN
# ============================================================================

def main():
    """Main compression workflow"""
    print("=" * 70)
    print("ESP HTTP ETag Asset Compression Tool")
    print("=" * 70)

    # Find configuration file
    config_file = find_config_file()
    if config_file is None:
        return 1

    print(f"Using config: {config_file}")

    # Load configuration
    config_root, targets = load_config(config_file)
    if not targets:
        print("ERROR: No targets defined in configuration file")
        return 1

    if config_root:
        print(f"Config root: {config_root}")
    print()

    total_files = 0
    skipped_dirs = []

    # Process each directory from config
    for rel_dir, file_patterns in targets:
        # Resolve target directory using flexible strategy
        target_dir = resolve_target_directory(rel_dir, config_root)

        if not target_dir:
            skipped_dirs.append(rel_dir)
            print(f"SKIP: Directory not found: {rel_dir}")
            continue

        print(f"Processing: {rel_dir}/ -> {target_dir}")
        results = process_files(target_dir, file_patterns)

        if results:
            output_path = target_dir / "etags.h"
            write_header_file(output_path, results)
            total_files += len(results)

        print()

    # Summary
    print("=" * 70)
    if total_files > 0:
        print(f"SUCCESS: Compressed {total_files} files")
        if skipped_dirs:
            print(f"\nSkipped {len(skipped_dirs)} directories (not found):")
            for d in skipped_dirs:
                print(f"  - {d}")
        print("\nNext steps:")
        print("  1. Include etags.h in your HTTP server handlers")
        print("  2. Use DECLARE_EMBEDDED_FILE() to declare embedded files")
        print("  3. Use SEND_REGISTERED_BINARY() to serve files with ETags")
    else:
        print("WARNING: No files were processed")
        if skipped_dirs:
            print(f"\nAll {len(skipped_dirs)} target directories were not found")
    print("=" * 70)

    return 0 if total_files > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
